-- ============================================================
-- V1 :: Initial ERP schema
-- Portable SQL: runs on PostgreSQL (prod) and H2/PostgreSQL-mode (dev/test)
-- Hibernate is in `validate` mode: it checks this schema, never changes it.
-- ============================================================

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role       VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE suppliers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    email      VARCHAR(160),
    phone      VARCHAR(40),
    address    VARCHAR(255),
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE customers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    email      VARCHAR(160),
    phone      VARCHAR(40),
    address    VARCHAR(255),
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE products (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku               VARCHAR(40)   NOT NULL,
    name              VARCHAR(160)  NOT NULL,
    category          VARCHAR(80),
    unit_price        NUMERIC(12,2) NOT NULL,
    quantity_in_stock INT           NOT NULL,
    reorder_level     INT           NOT NULL,
    supplier_id       BIGINT,
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP     NOT NULL,
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers
);

CREATE TABLE purchase_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(30)   NOT NULL,
    status       VARCHAR(20)   NOT NULL,
    order_date   TIMESTAMP     NOT NULL,
    total        NUMERIC(14,2) NOT NULL,
    supplier_id  BIGINT        NOT NULL,
    CONSTRAINT uk_purchase_orders_number UNIQUE (order_number),
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers
);

CREATE TABLE purchase_order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity   INT           NOT NULL,
    unit_cost  NUMERIC(12,2) NOT NULL,
    order_id   BIGINT        NOT NULL,
    product_id BIGINT        NOT NULL,
    CONSTRAINT fk_poi_order FOREIGN KEY (order_id) REFERENCES purchase_orders,
    CONSTRAINT fk_poi_product FOREIGN KEY (product_id) REFERENCES products
);

CREATE TABLE sales_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(30)   NOT NULL,
    status       VARCHAR(20)   NOT NULL,
    order_date   TIMESTAMP     NOT NULL,
    total        NUMERIC(14,2) NOT NULL,
    customer_id  BIGINT        NOT NULL,
    CONSTRAINT uk_sales_orders_number UNIQUE (order_number),
    CONSTRAINT fk_so_customer FOREIGN KEY (customer_id) REFERENCES customers
);

CREATE TABLE sales_order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity   INT           NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    order_id   BIGINT        NOT NULL,
    product_id BIGINT        NOT NULL,
    CONSTRAINT fk_soi_order FOREIGN KEY (order_id) REFERENCES sales_orders,
    CONSTRAINT fk_soi_product FOREIGN KEY (product_id) REFERENCES products
);
